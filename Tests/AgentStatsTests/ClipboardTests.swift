@MainActor @Suite(.serialized) struct ClipboardStoreTests {
    private func withBoard(_ body: (NSPasteboard) throws -> Void) rethrows {
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        try body(board)
    }

    private func put(_ text: String, on board: NSPasteboard, marks: [String] = []) {
        board.clearContents()
        board.setString(text, forType: .string)
        for mark in marks { board.setData(Data(), forType: NSPasteboard.PasteboardType(mark)) }
    }

    private func store(_ board: NSPasteboard, directory: URL? = nil, access: ClipboardAccess = .allowed,
                       app: String = "com.example.editor") -> ClipboardStore {
        ClipboardStore(pasteboard: board, directory: directory, defaults: nil, accessOverride: access, frontApp: { app })
    }

    @Test func offByDefault() {
        withBoard { board in
            let s = store(board)
            put("segredo", on: board)
            s.poll()
            #expect(!s.enabled)
            #expect(s.items.isEmpty)
        }
    }

    @Test func onlyWhatIsCopiedAfterTurningOn() {
        withBoard { board in
            put("antes", on: board)
            let s = store(board)
            s.setEnabled(true)
            s.poll()
            #expect(s.items.isEmpty)
            put("depois", on: board)
            s.poll()
            #expect(s.items.map(\.text) == ["depois"])
            s.setEnabled(false)
            put("desligado", on: board)
            s.poll()
            s.setEnabled(true)
            s.poll()
            #expect(s.items.map(\.text) == ["depois"])
        }
    }

    @Test(arguments: ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                      "org.nspasteboard.AutoGeneratedType", "com.apple.is-remote-clipboard"])
    func markedContentIsIgnored(mark: String) {
        withBoard { board in
            let s = store(board)
            s.setEnabled(true)
            put("password", on: board, marks: [mark])
            s.poll()
            #expect(s.items.isEmpty)
        }
    }

    @Test func passwordManagerIsIgnoredEvenAfterSwitchingApps() {
        withBoard { board in
            var app = "com.1password.1password"
            let s = ClipboardStore(pasteboard: board, directory: nil, defaults: nil, accessOverride: .allowed, frontApp: { app })
            s.setEnabled(true)
            s.poll()
            put("password sem marca", on: board)
            app = "com.example.browser"   // mudou de app antes da volta seguinte
            s.poll()
            #expect(s.items.isEmpty)
        }
    }

    @Test(arguments: [ClipboardAccess.notRequested, .asks, .denied])
    func withoutPermissionNothingIsKept(access: ClipboardAccess) {
        withBoard { board in
            let s = store(board, access: access)
            s.setEnabled(true)
            put("texto", on: board)
            s.poll()
            #expect(s.items.isEmpty)
        }
    }

    @Test func copyingFromThePanelIsNotANewEntry() {
        withBoard { board in
            let s = store(board)
            s.setEnabled(true)
            s.copy("snippet")
            s.poll()
            #expect(board.string(forType: .string) == "snippet")
            #expect(s.items.isEmpty)
        }
    }

    @Test func historyAndSnippetsSurviveARestartPrivately() throws {
        try withBoard { board in
            let dir = FileManager.default.temporaryDirectory.appendingPathComponent("clip-\(UUID().uuidString)")
            defer { try? FileManager.default.removeItem(at: dir) }
            let s = store(board, directory: dir)
            s.setEnabled(true)
            put("guardado", on: board)
            s.poll()
            s.draft = Snippet(name: "  ", text: "linha um\nlinha dois")
            s.saveDraft()

            let again = store(board, directory: dir)
            #expect(again.items.map(\.text) == ["guardado"])
            #expect(again.snippets.map(\.name) == ["linha um linha dois"])
            for file in ["clipboard.json", "snippets.json"] {
                let attributes = try FileManager.default.attributesOfItem(atPath: dir.appendingPathComponent(file).path)
                #expect((attributes[.posixPermissions] as? NSNumber)?.intValue == 0o600)
            }
            let values = try dir.appendingPathComponent("clipboard.json").resourceValues(forKeys: [.isExcludedFromBackupKey])
            #expect(values.isExcludedFromBackup == true)

            again.clearHistory()
            #expect(store(board, directory: dir).items.isEmpty)
            #expect(store(board, directory: dir).snippets.count == 1)
        }
    }

    @Test func unreadableSnippetsAreNeverOverwritten() throws {
        try withBoard { board in
            let dir = FileManager.default.temporaryDirectory.appendingPathComponent("clip-\(UUID().uuidString)")
            try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
            defer { try? FileManager.default.removeItem(at: dir) }
            let file = dir.appendingPathComponent("snippets.json")
            try Data("{estragado".utf8).write(to: file)
            let s = store(board, directory: dir)
            #expect(s.storageError != nil)
            s.draft = Snippet(name: "novo", text: "x")
            s.saveDraft()
            #expect(try Data(contentsOf: file) == Data("{estragado".utf8))
        }
    }

    @Test func demoForScreenshotsWritesNothing() {
        withBoard { board in
            let dir = FileManager.default.temporaryDirectory.appendingPathComponent("clip-\(UUID().uuidString)")
            let s = store(board, directory: dir)
            s.loadDemo()
            s.clearHistory()
            #expect(!FileManager.default.fileExists(atPath: dir.path))
        }
    }

    @Test func editMenuHasTheShortcuts() {
        let menu = EditMenu.make().items.first?.submenu
        #expect(menu?.items.map(\.keyEquivalent) == ["z", "Z", "x", "c", "v", "a"])
    }
}

@Suite struct ClipboardRulesTests {
    private let now = Date(timeIntervalSince1970: 1_800_000_000)

    // Montadas aos bocados: inteiras, o push protection do GitHub tomava-as por chaves reais.
    // Uma a uma, com tipo explícito: num só array o compilador desistia.
    private static func fake(_ head: String, _ tail: String, _ count: Int = 1) -> String {
        head + String(repeating: tail, count: count)
    }

    private static var secrets: [String] {
        var out: [String] = []
        out.append(fake("sk" + "-ant-", "a", 30))
        out.append(fake("ghp" + "_", "b", 36))
        out.append(fake("AK" + "IA", "C", 16))
        out.append(fake("sk" + "_live_", "d", 24))
        out.append(fake("xox" + "b-", "1", 12))
        out.append(fake("-----BEGIN ", "OPENSSH PRIVATE KEY-----"))
        out.append(fake("export TOKEN=" + "ghp" + "_", "e", 36))
        return out
    }

    @Test(arguments: secrets)
    func knownSecretsAreNotKept(text: String) {
        #expect(!ClipboardRules.shouldKeep(text))
    }

    @Test(arguments: ["olá", "task-list-para-a-semana", "https://example.com/a?b=c", "git commit -m 'x'"])
    func ordinaryTextIsKept(text: String) {
        #expect(ClipboardRules.shouldKeep(text))
    }

    @Test func blankAndHugeTextAreNotKept() {
        #expect(!ClipboardRules.shouldKeep("  \n "))
        #expect(!ClipboardRules.shouldKeep(String(repeating: "a", count: ClipboardRules.maxBytes + 1)))
    }

    @Test func copyingAgainMovesUpAndKeepsThePin() {
        let old = [ClipItem(text: "b", date: now), ClipItem(text: "a", date: now, pinned: true)]
        let out = ClipboardRules.adding("a", to: old, now: now.addingTimeInterval(5))
        #expect(out.map(\.text) == ["a", "b"])
        #expect(out[0].pinned)
        #expect(out[0].id == old[1].id)
    }

    @Test func oldAndExtraItemsLeaveButPinnedStay() {
        let recent = (0..<120).map { ClipItem(text: "\($0)", date: now) }
        let old = ClipItem(text: "velho", date: now.addingTimeInterval(-8 * 86_400))
        let pinned = ClipItem(text: "afixado", date: now.addingTimeInterval(-90 * 86_400), pinned: true)
        let out = ClipboardRules.pruned(recent + [old, pinned], now: now)
        #expect(out.count == ClipboardRules.maxItems + 1)
        #expect(out.last?.text == "afixado")
    }
}
