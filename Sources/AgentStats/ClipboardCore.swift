import Foundation

struct ClipItem: Codable, Identifiable, Equatable, Sendable {
    var id = UUID()
    var text: String
    var date: Date
    var pinned = false
}

struct Snippet: Codable, Identifiable, Equatable, Sendable {
    var id = UUID()
    var name: String
    var text: String
}

/// O que pode entrar no histórico, e por quanto tempo. Sem AppKit, para se testar sem clipboard.
enum ClipboardRules {
    static let maxItems = 100
    static let maxBytes = 50_000
    static let retention: TimeInterval = 7 * 86_400

    /// Marcas com que as apps dizem "isto não é para guardar" (nspasteboard.org e equivalentes antigas).
    static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "com.agilebits.onepassword",
        "Pasteboard generator type",
        // Clipboard universal: lê-lo ia buscar o conteúdo ao outro aparelho e bloqueava a app.
        "com.apple.is-remote-clipboard",
    ]

    /// Gestores de passwords: o que se copia com eles à frente nunca entra, mesmo sem a marca.
    static let privateApps = [
        "com.1password", "com.agilebits", "com.bitwarden", "com.apple.passwords", "com.apple.keychainaccess",
        "org.keepassxc", "com.lastpass", "com.dashlane", "in.sinew.enpass", "com.nordpass",
        "me.proton.pass", "com.markmcguill.strongbox",
    ]

    private static let secretPatterns = [
        #"-----BEGIN [A-Z ]*PRIVATE KEY"#,
        #"\bsk-[A-Za-z0-9_-]{20,}"#,              // OpenAI, Anthropic
        #"\b[sr]k_live_[A-Za-z0-9]{16,}"#,        // Stripe
        #"\bgh[pousr]_[A-Za-z0-9]{30,}"#,
        #"\bgithub_pat_[A-Za-z0-9_]{40,}"#,
        #"\bxox[abprs]-[A-Za-z0-9-]{10,}"#,
        #"\bAKIA[0-9A-Z]{16}\b"#,
        #"\bAIza[A-Za-z0-9_-]{35}"#,
        #"\beyJ[A-Za-z0-9_-]{10,}\.eyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}"#,   // JWT
    ]

    /// Decide-se antes de ler o conteúdo: só com os tipos e as apps que estiveram à frente.
    static func shouldRead(types: [String], apps: [String]) -> Bool {
        guard !types.contains(where: privateTypes.contains) else { return false }
        return !apps.contains { app in
            let id = app.lowercased()
            return privateApps.contains { id.hasPrefix($0) }
        }
    }

    static func shouldKeep(_ text: String) -> Bool {
        guard text.utf8.count <= maxBytes, !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return false }
        return !secretPatterns.contains { text.range(of: $0, options: .regularExpression) != nil }
    }

    /// O mais recente primeiro. Copiar outra vez o mesmo texto sobe-o, sem duplicar nem perder o alfinete.
    static func adding(_ text: String, to items: [ClipItem], now: Date) -> [ClipItem] {
        var out = items
        var item = ClipItem(text: text, date: now)
        if let i = out.firstIndex(where: { $0.text == text }) {
            item = out.remove(at: i)
            item.date = now
        }
        out.insert(item, at: 0)
        return pruned(out, now: now)
    }

    /// Os afixados não expiram nem contam para o limite.
    static func pruned(_ items: [ClipItem], now: Date) -> [ClipItem] {
        var loose = 0
        return items.filter { item in
            if item.pinned { return true }
            guard now.timeIntervalSince(item.date) < retention, loose < maxItems else { return false }
            loose += 1
            return true
        }
    }

    static func preview(_ text: String) -> String {
        String(text.prefix(300)).split(whereSeparator: \.isWhitespace).joined(separator: " ")
    }
}

/// JSON legível só pelo utilizador (0600) e fora das cópias de segurança do Time Machine.
enum PrivateFile {
    enum Loaded<T> {
        case missing
        case value(T)
        case unreadable
    }

    static func load<T: Decodable>(_ type: T.Type, from url: URL) -> Loaded<T> {
        guard FileManager.default.fileExists(atPath: url.path) else { return .missing }
        guard let data = try? Data(contentsOf: url), let value = try? JSONDecoder().decode(type, from: data) else { return .unreadable }
        return .value(value)
    }

    /// O ficheiro temporário já nasce com 0600: nunca há um instante em que outros o possam ler.
    @discardableResult
    static func save<T: Encodable>(_ value: T, to url: URL, backup: Bool) -> Bool {
        let fm = FileManager.default
        guard let data = try? JSONEncoder().encode(value) else { return false }
        do {
            try fm.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
            let temp = url.deletingLastPathComponent().appendingPathComponent(".\(url.lastPathComponent).\(UUID().uuidString)")
            guard fm.createFile(atPath: temp.path, contents: data, attributes: [.posixPermissions: 0o600]) else { return false }
            guard rename(temp.path, url.path) == 0 else {
                try? fm.removeItem(at: temp)
                return false
            }
            if !backup {
                var target = url
                var values = URLResourceValues()
                values.isExcludedFromBackup = true
                try? target.setResourceValues(values)
            }
            return true
        } catch {
            return false
        }
    }
}
